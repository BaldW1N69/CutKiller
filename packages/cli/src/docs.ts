/**
 * Generated reference pages: `pnpm docs` writes docs/rules.md from the rule
 * table and the shipped profiles, so the documentation cannot drift from code.
 */
import { writeFile } from "node:fs/promises";
import { measuredOnLabel, RULES, ruleThreshold } from "@cutkiller/qa";
import { loadProfile } from "@cutkiller/style";

const PROFILES = ["short", "long", "cinematic", "cinematic-short"] as const;
const CATEGORY = {
  montage: "Editing",
  motion: "Motion",
  captions: "Captions",
  audio: "Audio",
  image: "Image",
};

export async function writeRulesReference(path: string): Promise<void> {
  process.env.CUTKILLER_LANG = "en";
  const profiles = await Promise.all(PROFILES.map((p) => loadProfile(p)));
  const lines = [
    "# Quality rules",
    "",
    "<!-- Generated by `pnpm docs` from packages/qa/src/rules.ts and profiles/*.yaml. Do not edit by hand. -->",
    "",
    "Every render is checked against these 26 rules. Each category weighs 20 points; the score /100 is the weighted share of compliant items over the rules that apply to the video (a rule with nothing to check, e.g. ducking without music, is *not evaluated* and excluded; the report shows the coverage).",
    "",
    "Thresholds come from the style profile, never from code: the table shows each shipped profile's values. Override any of them in your own `.yaml` profile.",
    "",
    "**Measured on** says what the check reads: *render* is an independent measurement of the delivered file; *EDL*, *render log* and *presets* verify the plan the renderer executed.",
    "",
  ];
  for (const cat of Object.keys(CATEGORY) as (keyof typeof CATEGORY)[]) {
    lines.push(`## ${CATEGORY[cat]}`, "");
    for (const r of RULES.filter((x) => x.category === cat)) {
      lines.push(
        `### \`${r.id}\` — ${r.titleEn}`,
        "",
        `Weight **${r.weight}** · measured on ${measuredOnLabel(r.measuredOn)}`,
        "",
      );
      const values = profiles.map((p) => ruleThreshold(r.id, p));
      if (values.every((v) => v === values[0])) lines.push(`Threshold (all profiles): ${values[0]}`, "");
      else {
        lines.push("| Profile | Threshold |", "|---|---|");
        for (const [i, name] of PROFILES.entries()) lines.push(`| \`${name}\` | ${values[i]} |`);
        lines.push("");
      }
    }
  }
  await writeFile(path, `${lines.join("\n")}\n`);
}
