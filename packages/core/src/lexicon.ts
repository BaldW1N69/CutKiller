/** Languages with hesitation lists, an aligner and number spelling. */
export const SUPPORTED_LANGUAGES = Object.keys(LEXICONS);

/** Hesitations heard in every language (Whisper writes them the same way). */
const GENERIC: Lexicon = {
  fillerWords: ["hmm", "mm", "mmm", "uh", "um"],
  contextualFillers: [],
  emphasisWords: [],
  stopWords: [],
};

export function lexicon(language: string | undefined): Lexicon {
  return (language && LEXICONS[language.toLowerCase().slice(0, 2)]) || GENERIC;
}

const same = (a: readonly string[], b: readonly string[]) =>
  a.length === b.length && a.every((x, i) => x === b[i]);

/**
 * The profile with the word lists of `language`. A list still equal to the French
 * default is replaced; a list the profile customised is kept as written.
 */
export function localizeProfile(profile: StyleProfile, language: string | undefined): StyleProfile {
  if (!language || language.toLowerCase().startsWith("fr")) return profile;
  const lex = lexicon(language);
  const pick = (current: readonly string[], fr: readonly string[], next: readonly string[]) =>
    same(current, fr) ? [...next] : [...current];
  return {
    ...profile,
    montage: {
      ...profile.montage,
      fillerWords: pick(profile.montage.fillerWords, FRENCH.fillerWords, lex.fillerWords),
      contextualFillers: pick(
        profile.montage.contextualFillers,
        FRENCH.contextualFillers,
        lex.contextualFillers,
      ),
    },
    motion: {
      ...profile.motion,
      emphasisWords: pick(profile.motion.emphasisWords, FRENCH.emphasisWords, lex.emphasisWords),
      stopWords: pick(profile.motion.stopWords, FRENCH.stopWords, lex.stopWords),
    },
  };
}

/** Language spoken in most of the transcribed speech (by word count). */
export function dominantLanguage(
  transcripts: Readonly<Record<string, { language: string; words: readonly unknown[] }>> | undefined,
): string | undefined {
  let best: string | undefined;
  const count = new Map<string, number>();
  for (const t of Object.values(transcripts ?? {})) {
    const n = (count.get(t.language) ?? 0) + t.words.length;
    count.set(t.language, n);
    if (!best || n > (count.get(best) ?? 0)) best = t.language;
  }
  return best;
}
